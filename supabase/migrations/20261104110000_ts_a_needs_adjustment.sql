-- TS-a Time clock data for the per-person timesheet (Fred 2026-11-04, Part 2 of the Pay periods / Time clock
-- brief, SPEC §9.1 TS-a):
--  1. A forgotten clock-out no longer gets an arbitrary time that counts as worked. The system still writes
--     the clock-out (so the person is clocked out next morning and the 8 PM alerts stop) but marks it
--     needs_adjustment: the shift counts 0 minutes until someone types the real end time or accepts the
--     suggested one (the last recorded activity of the day, as TC-d computed it).
--  2. Each shift (its clock-in) can carry the job it was for and a manager's note.
--  3. Time off, the basics only: one row per person and day with the type, paid or not, the hours and a note
--     (balances, requests and policies are Stage 4 of the 2026-10-29 brief, still to come).

alter table public.time_entries add column needs_adjustment boolean not null default false;
comment on column public.time_entries.needs_adjustment is 'TS-a: a clock-out the system wrote with a suggested time; the shift counts 0 until the office sets the real time or accepts the suggestion';
alter table public.time_entries add column project_id bigint references public.projects (id) on delete set null;
comment on column public.time_entries.project_id is 'TS-a: on a clock-in, the job the shift was for (set by hand; otherwise the job of the check-ins inside the shift is shown)';
alter table public.time_entries add column manager_note text;
comment on column public.time_entries.manager_note is 'TS-a: on a clock-in, the office''s note about the shift';
create index on public.time_entries (employee_id) where needs_adjustment;

-- The 34 auto clock-outs written so far (TC-d / F20-b) whose shift nobody has reviewed become "needs adjustment"
-- (Fred 2026-11-04, answer 5); the reviewed ones stay as they are.
update public.time_entries o
set needs_adjustment = true
where o.kind = 'clock_out' and o.auto_closed and o.deleted_at is null and o.pay_period_id is null
  and (select i.reviewed_at from public.time_entries i
       where i.employee_id = o.employee_id and i.kind = 'clock_in' and i.at < o.at and i.deleted_at is null
       order by i.at desc limit 1) is null;

create table public.time_off_entries (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  day date not null,
  kind text not null check (kind in ('Day off', 'Vacation', 'Sick', 'Holiday', 'Personal', 'Unpaid')),
  paid boolean not null default true,
  minutes integer not null default 480 check (minutes between 0 and 1440),
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create unique index time_off_entries_one_per_day on public.time_off_entries (employee_id, day) where deleted_at is null;
comment on table public.time_off_entries is 'TS-a: time off per person and day (type, paid, hours); paid hours reach Pay periods as PTO';
create trigger time_off_entries_touch before update on public.time_off_entries for each row execute function app.touch_updated_at();
alter table public.time_off_entries enable row level security;
create policy "employee viewers read time off" on public.time_off_entries for select to authenticated
  using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "employee editors add time off" on public.time_off_entries for insert to authenticated with check (app.has_permission('administrative.employees.modify'));
create policy "employee editors change time off" on public.time_off_entries for update to authenticated using (app.has_permission('administrative.employees.modify')) with check (app.has_permission('administrative.employees.modify'));
grant select, insert, update on public.time_off_entries to authenticated;
