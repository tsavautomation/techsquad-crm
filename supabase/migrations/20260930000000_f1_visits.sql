insert into public.group_permissions (group_id, permission_key)
select g.id, k
from public.groups g
cross join unnest(array['schedule.visits.view_page', 'schedule.visits.view_all', 'schedule.visits.create', 'schedule.visits.modify', 'schedule.visits.delete', 'schedule.visits.archive']) k
where g.slug in ('admin', 'office_management', 'coo', 'project_manager', 'treasurer');

insert into public.group_permissions (group_id, permission_key)
select g.id, k
from public.groups g
cross join unnest(array['schedule.visits.view_page', 'schedule.visits.view_all']) k
where g.slug = 'technician';
