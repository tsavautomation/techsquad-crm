-- ---------------------------------------------------------------- sms outbox
create table public.sms_outbox (
  id uuid primary key default gen_random_uuid(),
  kind text not null default 'report_reminder',
  employee_id bigint references public.employees (id) on delete set null,
  visit_id bigint references public.visits (id) on delete set null,
  to_number text not null,
  body text not null,
  status text not null default 'queued' check (status in ('queued', 'sent', 'failed')),
  test_mode boolean not null default false,
  provider_id text,
  error text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);
create index sms_outbox_status_idx on public.sms_outbox (status, created_at);
create index sms_outbox_employee_idx on public.sms_outbox (employee_id, created_at desc);
alter table public.sms_outbox enable row level security;
create policy "office reads" on public.sms_outbox for select to authenticated using ((select app.can_view_all('report_deficiencies')));

