-- F18 Visit = Report rule (SPEC §9.1 F18-a…d).
--
--   report_deficiencies   one row per person and visit when the Job Report was Late or Missing;
--                         Admin / COO can excuse it with a reason (History keeps the audit)
--   sms_outbox            every SMS (Twilio), queued → sent / failed; test mode like email
--   automations 900601    the nightly jobs run as this row (9 PM reminders, midnight close) → automation_runs
--   automations 900602    a Job Report added: the Late check (action report_rule)
--   app_settings field_day.report_rule   { mode: off | dry_run | live, since: date }

-- ---------------------------------------------------------------- report deficiencies
create table public.report_deficiencies (
  id bigint generated by default as identity primary key,
  title text,
  employee_id bigint not null references public.employees (id) on delete cascade,
  date date not null,
  project_id bigint references public.projects (id) on delete set null,
  visit_id bigint references public.visits (id) on delete set null,
  type text not null check (type in ('Late', 'Missing')),
  status text not null default 'Open' check (status in ('Open', 'Excused')),
  report_id bigint references public.job_reports (id) on delete set null,
  performance_id bigint references public.staff_performance (id) on delete set null,
  excuse_reason text,
  excused_by uuid references public.profiles (id) on delete set null,
  excused_at timestamptz,
  locked boolean not null default false,
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null,
  archived_at timestamptz,
  deleted_at timestamptz,
  unique (employee_id, visit_id)
);
comment on table public.report_deficiencies is 'Report Deficiencies — a Job Report that was Late or Missing for a visit (F18, not from WebAuthor)';
create index on public.report_deficiencies (employee_id, date desc);
create index on public.report_deficiencies (project_id);
create index on public.report_deficiencies (status);

insert into app.record_types (table_name, label, module, resource, parent_table, parent_column, lock_resource, sensitive_columns)
values ('report_deficiencies', 'Report Deficiencies', 'administrative', 'report-deficiencies', null, null, null, '{}');

create trigger before_write before insert or update on public.report_deficiencies for each row execute function app.record_before_write();
create trigger audit after insert or update on public.report_deficiencies for each row execute function app.record_audit();

alter table public.report_deficiencies enable row level security;
create policy "view" on public.report_deficiencies for select to authenticated using ((select app.can_view_all('report_deficiencies')) or (created_by = (select auth.uid()) and (select app.can_view_page('report_deficiencies'))));
create policy "create" on public.report_deficiencies for insert to authenticated with check ((select app.can_do('report_deficiencies', 'create')));
create policy "modify" on public.report_deficiencies for update to authenticated using (((select app.can_view_all('report_deficiencies')) or (created_by = (select auth.uid()) and (select app.can_view_page('report_deficiencies')))) and ((select app.can_do('report_deficiencies', 'modify')) or (select app.can_do('report_deficiencies', 'delete')) or (select app.can_do('report_deficiencies', 'archive')))) with check (((select app.can_do('report_deficiencies', 'modify')) or (select app.can_do('report_deficiencies', 'delete')) or (select app.can_do('report_deficiencies', 'archive'))));

