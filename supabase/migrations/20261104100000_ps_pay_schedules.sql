-- PS-a Pay schedules (Fred 2026-11-04, SPEC §9.1 PS-a): the Tech Squad pays in week-based cycles that start on a
-- date of each group's own, not on the calendar. One global biweekly anchor and a pay frequency per employee
-- (TC-e) become pay schedules: a named group with a frequency (Biweekly = 14 days, Every 4 weeks = 28 days,
-- Monthly calendar as a secondary option), an anchor date (the first day of its first period; its weekday is the
-- cut day) and a pay-day rule (N days after the period ends, or a fixed weekday after it). Each employee is
-- linked to a schedule from a date on (history kept, so a person can change group without breaking earlier
-- periods), and one period's pay day can be moved (a holiday) without touching the cycle.
-- Nothing here holds amounts; pay rates and locked periods keep their own confidential rules (TC-g).

-- 1. The schedules.
create table public.pay_schedules (
  id bigint generated by default as identity primary key,
  name text not null unique,
  frequency text not null check (frequency in ('Biweekly', 'Every 4 weeks', 'Monthly calendar')),
  anchor_on date not null,
  pay_day_rule jsonb not null default '{"kind": "days_after", "days": 5}',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now()
);
comment on table public.pay_schedules is 'PS-a: a pay group: frequency, anchor date (first period start; its weekday is the cut day) and the pay-day rule';
comment on column public.pay_schedules.pay_day_rule is '{"kind":"days_after","days":N} = N days after the period ends; {"kind":"weekday","weekday":0-6} = the first such weekday after the period ends (0 = Sunday)';
create trigger pay_schedules_touch before update on public.pay_schedules for each row execute function app.touch_updated_at();
alter table public.pay_schedules enable row level security;
create policy "employee viewers read pay schedules" on public.pay_schedules for select to authenticated
  using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "job costing manages pay schedules" on public.pay_schedules for insert to authenticated with check (app.has_permission('job_costing.view'));
create policy "job costing changes pay schedules" on public.pay_schedules for update to authenticated using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
grant select, insert, update on public.pay_schedules to authenticated;

-- 2. Which schedule each employee is on, from a date on (null schedule = not paid through pay periods from then).
create table public.employee_pay_schedules (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  schedule_id bigint references public.pay_schedules (id) on delete restrict,
  effective_from date not null,
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  unique (employee_id, effective_from)
);
create index on public.employee_pay_schedules (employee_id, effective_from desc);
comment on table public.employee_pay_schedules is 'PS-a: the pay schedule a person is on from a date (history); the row in force on a period''s first day decides';
alter table public.employee_pay_schedules enable row level security;
create policy "employee viewers read pay schedule links" on public.employee_pay_schedules for select to authenticated
  using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "employee editors add pay schedule links" on public.employee_pay_schedules for insert to authenticated with check (app.has_permission('administrative.employees.modify'));
create policy "employee editors change pay schedule links" on public.employee_pay_schedules for update to authenticated using (app.has_permission('administrative.employees.modify')) with check (app.has_permission('administrative.employees.modify'));
create policy "employee editors remove pay schedule links" on public.employee_pay_schedules for delete to authenticated using (app.has_permission('administrative.employees.modify'));
grant select, insert, update, delete on public.employee_pay_schedules to authenticated;

-- 3. A moved pay day for one period of a schedule (a holiday), keyed by the period's first day.
create table public.pay_period_overrides (
  id bigint generated by default as identity primary key,
  schedule_id bigint not null references public.pay_schedules (id) on delete cascade,
  starts_on date not null,
  pay_day date not null,
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  unique (schedule_id, starts_on)
);
comment on table public.pay_period_overrides is 'PS-a: one period''s pay day moved by hand; the cycle itself is unchanged';
alter table public.pay_period_overrides enable row level security;
create policy "job costing manages pay day overrides" on public.pay_period_overrides for all to authenticated
  using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
grant select, insert, update, delete on public.pay_period_overrides to authenticated;

-- 4. Locked periods belong to a schedule (no period has been locked yet, so no backfill).
alter table public.pay_periods add column schedule_id bigint not null references public.pay_schedules (id) on delete restrict;
alter table public.pay_periods drop constraint pay_periods_frequency_check;
alter table public.pay_periods drop constraint pay_periods_frequency_starts_on_key;
alter table public.pay_periods add constraint pay_periods_frequency_check check (frequency in ('Biweekly', 'Every 4 weeks', 'Monthly calendar'));
alter table public.pay_periods add unique (schedule_id, starts_on);

-- 5. Today's groups: the biweekly cycle from Monday 2026-10-12 paid 5 days after (TC-e's settings), and the
--    office's 4-week cycle from a Friday, paid on the Friday that completes the four weeks (Fred 2026-11-04; the
--    anchor Friday is Fred's to set on Pay periods › Pay schedules). The office people on Monthly move to it;
--    field technicians are linked one by one on the Employee page.
insert into public.pay_schedules (name, frequency, anchor_on, pay_day_rule) values
  ('Biweekly', 'Biweekly', '2026-10-12', '{"kind": "days_after", "days": 5}'),
  ('Every 4 weeks', 'Every 4 weeks', '2026-10-16', '{"kind": "weekday", "weekday": 5}');
insert into public.employee_pay_schedules (employee_id, schedule_id, effective_from, note)
select e.id, s.id, s.anchor_on, 'PS-a: moved from Monthly'
from public.employees e, public.pay_schedules s
where s.name = 'Every 4 weeks' and e.pay_frequency = 'Monthly' and e.deleted_at is null;

-- 6. The old per-employee frequency and the global settings are retired.
alter table public.employees drop column pay_frequency;
delete from public.app_settings where key = 'payroll';
