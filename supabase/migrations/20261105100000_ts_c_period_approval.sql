-- TS-c Timesheet approval per pay period and department (Fred 2026-11-04/05, Part 4 of the Pay periods / Time
-- clock brief; SPEC §9.1 TS-c). Replaces TC-h's approval per week (never used: 0 rows) and J-t's Monday
-- overtime tasks. A person's timesheet is approved for one pay-schedule period (PS-a), by the people with the
-- "Approve / reopen timesheets" permission (Saulo, Jessica), for the time-clock groups that need it (Admin ›
-- Field day: Field for now; the Office goes to Pay periods directly). An approved period is locked exactly as
-- an approved week was; reopening (with a reason) unlocks it. Pay periods take a Field line only once the
-- person's timesheet is approved.

-- 1. One person's period once approved (locked) or reopened; no row = Open.
create table public.timesheet_periods (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  schedule_id bigint not null references public.pay_schedules (id) on delete restrict,
  starts_on date not null,
  ends_on date not null check (ends_on >= starts_on),
  status text not null check (status in ('Approved', 'Reopened')),
  minutes_at_approval integer,
  approved_by uuid references public.profiles (id) on delete set null,
  approved_at timestamptz,
  reopened_by uuid references public.profiles (id) on delete set null,
  reopened_at timestamptz,
  reopen_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, starts_on)
);
create index on public.timesheet_periods (employee_id, starts_on, ends_on);
comment on table public.timesheet_periods is 'TS-c: one person''s pay period once its timesheet is approved (locked) or reopened; no row = Open';

create table public.timesheet_period_events (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.timesheet_periods (id) on delete cascade,
  action text not null check (action in ('approved', 'reopened')),
  minutes integer,
  reason text,
  by_user uuid references public.profiles (id) on delete set null,
  at timestamptz not null default now()
);
create index on public.timesheet_period_events (period_id);
comment on table public.timesheet_period_events is 'TS-c: who approved or reopened a person''s period, when, and why';

alter table public.timesheet_periods enable row level security;
alter table public.timesheet_period_events enable row level security;
create policy "timesheet readers see period status" on public.timesheet_periods for select to authenticated
  using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "approvers change period status" on public.timesheet_periods for insert to authenticated
  with check (app.has_permission('administrative.timesheets.approve'));
create policy "approvers update period status" on public.timesheet_periods for update to authenticated
  using (app.has_permission('administrative.timesheets.approve')) with check (app.has_permission('administrative.timesheets.approve'));
create policy "timesheet readers see period events" on public.timesheet_period_events for select to authenticated
  using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "approvers write period events" on public.timesheet_period_events for insert to authenticated
  with check (app.has_permission('administrative.timesheets.approve'));
grant select, insert, update on public.timesheet_periods to authenticated;
grant select, insert on public.timesheet_period_events to authenticated;

update public.permissions set label = 'Approve / reopen timesheets', description = 'Time clock › Timesheets: approve a person''s pay period (locks its clock entries) and reopen it with a reason'
where key = 'administrative.timesheets.approve';

