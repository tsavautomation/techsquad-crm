-- F29 (Fred 2026-10-22, "Always per person in and out"): On my way / check-in / check-out are recorded per person.
-- Until now a visit had one check-in: when one of the team pressed Check in, the whole team's cards read On site
-- (Daniel at 6:55 AM put Carlos, Jeferson and Hugo "on site" on the Builcore visit). Now each person on a visit
-- (technician or Also going) has their own row in visit_attendance; the visit's own on_way_at / checked_in_at /
-- checked_out_at / status stay as the TEAM SUMMARY (first on the way, first check-in, last check-out, On site while
-- anyone is there), so hours, costing, the portal, the reality check and the timeline keep reading them.

create table public.visit_attendance (
  id bigint generated by default as identity primary key,
  visit_id bigint not null references public.visits(id) on delete cascade,
  employee_id bigint not null references public.employees(id),
  user_id uuid,
  on_way_at timestamptz,
  checked_in_at timestamptz,
  checked_out_at timestamptz,
  auto_closed_at timestamptz,
  auto_closed_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (visit_id, employee_id)
);
create index visit_attendance_employee_idx on public.visit_attendance (employee_id, checked_in_at);
alter table public.visit_attendance enable row level security;
-- Who is on the way / on site is not sensitive: every signed-in user may read it (Today, the visit page, the office).
create policy "attendance readable" on public.visit_attendance for select to authenticated using (true);
grant select on public.visit_attendance to authenticated;
-- Writes only through the functions below (security definer) and the service role.

-- The team summary on the visit, from its attendance rows.
create or replace function public.visit_recompute(p_id bigint)
returns public.visits
language plpgsql security definer set search_path = ''
as $$
declare
  v public.visits;
  first_way timestamptz; first_in timestamptz; last_out timestamptz;
  anyone_on_site boolean; anyone_out boolean; anyone_way boolean;
begin
  select * into v from public.visits where id = p_id and deleted_at is null;
  if v.id is null then return v; end if;
  select min(on_way_at), min(checked_in_at), max(checked_out_at),
         bool_or(checked_in_at is not null and checked_out_at is null),
         bool_or(checked_out_at is not null),
         bool_or(on_way_at is not null)
    into first_way, first_in, last_out, anyone_on_site, anyone_out, anyone_way
    from public.visit_attendance where visit_id = p_id;
  perform set_config('app.engine', 'on', true);
  update public.visits
     set on_way_at = first_way,
         checked_in_at = first_in,
         checked_out_at = case when coalesce(anyone_on_site, false) then null else last_out end,
         status = case
           when status = 'Cancelled' then status
           when coalesce(anyone_on_site, false) then 'On site'
           when coalesce(anyone_out, false) then 'Done'
           when coalesce(anyone_way, false) then 'On the way'
           when status in ('On the way', 'On site', 'Done') then 'Scheduled'
           else status end,
         updated_by = coalesce(auth.uid(), updated_by)
   where id = p_id
   returning * into v;
  perform set_config('app.engine', 'off', true);
  return v;
end;
$$;
revoke all on function public.visit_recompute(bigint) from public, anon, authenticated;
grant execute on function public.visit_recompute(bigint) to service_role;

-- My Employee record among the people on this visit (technician or Also going), by login email.
create or replace function public.my_employee_on_visit(p_id bigint)
returns bigint
language sql security definer set search_path = '' stable
as $$
  select e.id from public.employees e
  join public.visits v on v.id = p_id
  where lower(e.email) = (select lower(email) from auth.users where id = auth.uid()) and e.deleted_at is null
    and (e.id = v.technician_id or e.id in (select target_id from public.visits_team where record_id = p_id))
  order by (e.id = v.technician_id) desc, e.id
  limit 1;
$$;
revoke all on function public.my_employee_on_visit(bigint) from public, anon, authenticated;

-- Check me out of every other visit I am still on (F20: one person in one place), per person now.
create or replace function public.close_my_open_visits(p_except bigint, p_reason text)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  me text := (select lower(email) from auth.users where id = auth.uid());
  n integer := 0;
  r record;
begin
  if me is null then return 0; end if;
  for r in
    update public.visit_attendance a
       set checked_out_at = now(), auto_closed_at = now(), auto_closed_reason = p_reason, updated_at = now()
     where a.employee_id in (select id from public.employees where lower(email) = me and deleted_at is null)
       and a.checked_in_at is not null and a.checked_out_at is null
       and a.visit_id <> coalesce(p_except, 0)
    returning a.visit_id
  loop
    perform public.visit_recompute(r.visit_id);
    n := n + 1;
  end loop;
  return n;
end;
$$;
grant execute on function public.close_my_open_visits(bigint, text) to authenticated;

-- One step for ME on this visit. Returns the visit with its team summary refreshed.
create or replace function public.visit_step(p_id bigint, p_step text)
returns public.visits
language plpgsql security definer set search_path = ''
as $$
declare
  v public.visits;
  me_id bigint;
  a public.visit_attendance;
  items jsonb;
begin
  select * into v from public.visits where id = p_id and deleted_at is null;
  if v.id is null then
    raise exception 'This visit no longer exists' using errcode = 'P0002';
  end if;
  me_id := public.my_employee_on_visit(p_id);
  if me_id is null then
    raise exception 'Only the people going on this visit can check in or out' using errcode = '42501';
  end if;
  if v.status = 'Cancelled' then
    raise exception 'This visit was cancelled' using errcode = '22023';
  end if;
  if p_step not in ('on_way', 'check_in', 'check_out') then
    raise exception 'Unknown step %', p_step using errcode = '22023';
  end if;

  insert into public.visit_attendance (visit_id, employee_id, user_id)
  values (p_id, me_id, auth.uid())
  on conflict (visit_id, employee_id) do update set user_id = coalesce(public.visit_attendance.user_id, excluded.user_id)
  returning * into a;

  if p_step = 'check_out' and a.checked_in_at is null then
    -- Left without pressing Check in: the arrival counts from now.
    a.checked_in_at := now();
  end if;
  if p_step = 'check_in' and a.checked_in_at is not null and a.checked_out_at is null then
    raise exception 'You are already checked in here' using errcode = '22023';
  end if;
  if p_step = 'check_out' and a.checked_out_at is not null then
    raise exception 'You already checked out of this visit' using errcode = '22023';
  end if;

  -- F20: one person on site in one place only.
  if p_step in ('on_way', 'check_in') then
    perform public.close_my_open_visits(p_id, 'next_visit');
  end if;

  update public.visit_attendance
     set on_way_at = case when p_step = 'on_way' then now() else on_way_at end,
         checked_in_at = case when p_step = 'check_in' then now() when p_step = 'check_out' then coalesce(a.checked_in_at, now()) else checked_in_at end,
         checked_out_at = case when p_step = 'check_out' then now() when p_step = 'check_in' then null else checked_out_at end,
         auto_closed_at = case when p_step = 'check_in' then null else auto_closed_at end,
         auto_closed_reason = case when p_step = 'check_in' then null else auto_closed_reason end,
         updated_at = now()
   where id = a.id;

  if p_step = 'check_in' then
    -- The service checklist lands on the visit once (F2).
    items := (select value -> 'service_lists' -> v.service_type -> 'checklist' from public.app_settings where key = 'field_day');
    if v.service_type is not null and jsonb_typeof(items) = 'array' then
      insert into public.record_checklist_items (table_name, record_id, item, source, created_by)
      select 'visits', p_id, trim(x), 'service:' || v.service_type, null
      from jsonb_array_elements_text(items) x
      where trim(x) <> ''
        and not exists (select 1 from public.record_checklist_items c where c.table_name = 'visits' and c.record_id = p_id and c.item = trim(x));
    end if;
  end if;

  return public.visit_recompute(p_id);
end;
$$;
grant execute on function public.visit_step(bigint, text) to authenticated;

-- J-n undo, per person: my On the way → nothing, my On site → the step before; my time-clock entries of that step go too.
create or replace function public.visit_undo_step(p_id bigint)
returns public.visits
language plpgsql security definer set search_path = ''
as $$
declare
  v public.visits;
  me_id bigint;
  a public.visit_attendance;
begin
  select * into v from public.visits where id = p_id and deleted_at is null;
  if v.id is null then
    raise exception 'This visit no longer exists' using errcode = 'P0002';
  end if;
  me_id := public.my_employee_on_visit(p_id);
  if me_id is null then
    raise exception 'Only the people going on this visit can undo a step' using errcode = '42501';
  end if;
  select * into a from public.visit_attendance where visit_id = p_id and employee_id = me_id;
  if a.id is not null and a.checked_in_at is not null and a.checked_out_at is null then
    update public.visit_attendance set checked_in_at = null, updated_at = now() where id = a.id;
    update public.time_entries set deleted_at = now() where visit_id = p_id and employee_id = me_id and kind = 'visit_in' and deleted_at is null;
  elsif a.id is not null and a.on_way_at is not null and a.checked_in_at is null then
    update public.visit_attendance set on_way_at = null, updated_at = now() where id = a.id;
    update public.time_entries set deleted_at = now() where visit_id = p_id and employee_id = me_id and kind = 'on_way' and deleted_at is null;
  else
    raise exception 'There is nothing to undo on this visit' using errcode = '22023';
  end if;
  return public.visit_recompute(p_id);
end;
$$;
grant execute on function public.visit_undo_step(bigint) to authenticated;

-- History: the visit-level times so far belong to the technician of the visit.
insert into public.visit_attendance (visit_id, employee_id, on_way_at, checked_in_at, checked_out_at, auto_closed_at, auto_closed_reason, created_at, updated_at)
select v.id, v.technician_id, v.on_way_at, v.checked_in_at, v.checked_out_at, v.auto_closed_at, v.auto_closed_reason, coalesce(v.on_way_at, v.checked_in_at, v.checked_out_at, now()), now()
from public.visits v
where v.technician_id is not null and v.deleted_at is null
  and (v.on_way_at is not null or v.checked_in_at is not null or v.checked_out_at is not null)
on conflict (visit_id, employee_id) do nothing;
