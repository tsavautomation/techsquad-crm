-- 2. Overtime days: one row per person and day whose excess passes the tolerance, in a group that needs the approval.
create table public.overtime_days (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  day date not null,
  worked_minutes integer not null,
  excess_minutes integer not null,
  status text not null default 'awaiting_justification' check (status in ('awaiting_justification', 'pending', 'approved', 'refused', 'void')),
  justification text,
  justified_at timestamptz,
  justify_due_at timestamptz,
  decided_by uuid references public.profiles (id) on delete set null,
  decided_at timestamptz,
  decision_comment text,
  auto_refused boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, day)
);
create index on public.overtime_days (status) where status in ('awaiting_justification', 'pending');
comment on table public.overtime_days is 'OT-b: a day''s overtime waiting for the technician''s justification and the approver''s decision; refused = the excess is not paid; void = the day no longer has overtime';
create trigger overtime_days_touch before update on public.overtime_days for each row execute function app.touch_updated_at();

create table public.overtime_day_events (
  id bigint generated by default as identity primary key,
  overtime_day_id bigint not null references public.overtime_days (id) on delete cascade,
  employee_id bigint not null references public.employees (id) on delete cascade,
  action text not null check (action in ('created', 'justified', 'approved', 'refused', 'auto_refused', 'reopened', 'updated', 'void')),
  minutes integer,
  note text,
  by_user uuid references public.profiles (id) on delete set null,
  at timestamptz not null default now()
);
create index on public.overtime_day_events (overtime_day_id, at);
comment on table public.overtime_day_events is 'OT-b: the history of an overtime day (who, when, the texts)';

alter table public.overtime_days enable row level security;
alter table public.overtime_day_events enable row level security;
-- Reads: the person their own; the office everyone''s. Writes go through the server (service role) after its own checks.
create policy "own or staff read overtime days" on public.overtime_days for select to authenticated
  using (employee_id = any (app.my_employee_ids()) or app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "own or staff read overtime events" on public.overtime_day_events for select to authenticated
  using (employee_id = any (app.my_employee_ids()) or app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
grant select on public.overtime_days, public.overtime_day_events to authenticated;

-- 3. Time off: two policies (paid / unpaid) and the absence without a request, all taken from one bank of hours.
alter table public.time_off_entries drop constraint time_off_entries_kind_check;
update public.time_off_entries set kind = case when paid then 'Paid absence' else 'Unpaid absence' end;
alter table public.time_off_entries add constraint time_off_entries_kind_check check (kind in ('Paid absence', 'Unpaid absence', 'Unrequested absence'));

create table public.time_off_requests (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  policy text not null check (policy in ('Paid absence', 'Unpaid absence')),
  starts_on date not null,
  ends_on date not null check (ends_on >= starts_on),
  minutes_per_day integer not null check (minutes_per_day between 60 and 1440),
  reason text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'refused', 'cancelled')),
  /** Entered by an approver for someone (approved at once). */
  direct boolean not null default false,
  decided_by uuid references public.profiles (id) on delete set null,
  decided_at timestamptz,
  decision_comment text,
  cancelled_by uuid references public.profiles (id) on delete set null,
  cancelled_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on public.time_off_requests (employee_id, starts_on);
create index on public.time_off_requests (status) where status = 'pending';
comment on table public.time_off_requests is 'TO-a: a time-off request (policy, dates, hours per day, reason) and its decision; approved = one time_off_entries row per weekday';
create trigger time_off_requests_touch before update on public.time_off_requests for each row execute function app.touch_updated_at();

alter table public.time_off_entries add column request_id bigint references public.time_off_requests (id) on delete set null;
alter table public.time_off_entries add column auto boolean not null default false;
comment on column public.time_off_entries.auto is 'TO-a: written by the system for a weekday with no clock-in and no time off (absence without a request)';

-- The bank: only what is typed by hand (the opening balance and the adjustments). The balance is computed:
-- these rows minus the time-off hours taken since the first one. Never stored.
create table public.time_off_bank_entries (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  day date not null default (now() at time zone 'America/New_York')::date,
  delta_minutes integer not null check (delta_minutes <> 0),
  kind text not null default 'adjustment' check (kind in ('opening', 'adjustment')),
  reason text not null,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create index on public.time_off_bank_entries (employee_id, day);
comment on table public.time_off_bank_entries is 'TO-a: the opening balance and manual adjustments (+/-) of a person''s time-off bank, in minutes, with who, when and why';

alter table public.time_off_requests enable row level security;
alter table public.time_off_bank_entries enable row level security;
create policy "own or staff read time off requests" on public.time_off_requests for select to authenticated
  using (employee_id = any (app.my_employee_ids()) or app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "own or staff read time off bank" on public.time_off_bank_entries for select to authenticated
  using (employee_id = any (app.my_employee_ids()) or app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "own time off entries" on public.time_off_entries for select to authenticated using (employee_id = any (app.my_employee_ids()));
grant select on public.time_off_requests, public.time_off_bank_entries to authenticated;

