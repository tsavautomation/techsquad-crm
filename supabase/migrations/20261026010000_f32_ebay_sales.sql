-- F32 Ebay sales (Fred 2026-10-26, "a dashboard under Inventory called Ebay … all ebay sales listed with item,
-- price sold, buyer and address to ship; the sale email and the shipping-label email under one tile; mark as
-- shipped and enter the tracking number"). Both eBay emails reach the CRM mailbox through cPanel filters on
-- info@tsav.net (From ebay@ebay.com + Subject "You made the sale" / "Your shipping label is ready" → Redirect to
-- tsavcrm@gmail.com); the five-minute check reads them here and trashes the Gmail copy.

create table public.ebay_sales (
  id bigint generated by default as identity primary key,
  order_number text unique,              -- eBay order number (12-34567-89012); the key both emails share
  item_id text,
  item_title text,
  quantity integer,
  price numeric(12,2),                   -- item price
  shipping numeric(12,2),
  total numeric(12,2),
  buyer_name text,
  buyer_username text,
  ship_to text,                          -- the address to ship to, as lines
  sold_at timestamptz,
  sale_mail_id bigint references public.mail_messages (id) on delete set null,
  label_mail_id bigint references public.mail_messages (id) on delete set null,
  label_url text,
  label_ready_at timestamptz,
  tracking text,
  status text not null default 'sold' check (status in ('sold', 'label_ready', 'shipped')),
  shipped_at timestamptz,
  shipped_by uuid references public.profiles (id) on delete set null,
  notes text,
  extraction text not null default 'ai' check (extraction in ('ai', 'fallback')),
  extraction_error text,
  raw_sale_text text,
  raw_label_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.ebay_sales is 'F32: one row per eBay sale, built from the "You made the sale" and "Your shipping label is ready" emails; worked on Inventory › Ebay';
create index ebay_sales_status_idx on public.ebay_sales (status, sold_at desc);
create trigger ebay_sales_touch before update on public.ebay_sales
  for each row execute function app.touch_updated_at();

-- Who sees the tab (Fred 2026-10-26): Roberto, Fred, Karina, Saulo, Jessica, Luana and Lucas; administrators always.
insert into public.permissions (key, module, resource, action, kind, area, label, description) values
  ('inventory.ebay.view_page', 'inventory', 'ebay', 'view_page', 'page', 'Ebay', 'Ebay', 'The Ebay sales board under Inventory: what to ship, mark shipped with the tracking number, history')
