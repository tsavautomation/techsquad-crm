select p.id, 'inventory.ebay.view_page' from public.profiles p
where lower(p.email) in ('roberto@tsav.net', 'fred@tsav.net', 'karina@tsav.net', 'saulo@tsav.net', 'jessica@tsav.net', 'luana@tsav.net', 'lucas@tsav.net')
