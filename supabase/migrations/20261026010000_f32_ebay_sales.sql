alter table public.ebay_sales enable row level security;
-- Rows are added by the mailbox check (service role); people with the tab read and work them.
create policy "ebay read" on public.ebay_sales for select to authenticated
  using ((select app.has_permission('inventory.ebay.view_page')));
create policy "ebay work" on public.ebay_sales for update to authenticated
  using ((select app.has_permission('inventory.ebay.view_page')))
  with check ((select app.has_permission('inventory.ebay.view_page')));
