-- F30 Logins & passwords (Fred 2026-10-22): the office's shared logins — shopping sites, Apple IDs, suppliers,
-- software — in one tab. Passwords and PINs are encrypted at rest and masked on screen (registry `sensitive`),
-- shown only to people who may change the record (the office); never in emails, PDFs, OneDrive or backups
-- (registry `privateFiles`). Every time someone reveals or copies a secret it is logged (sensitive_reveals).

create table public.credentials (
  id bigint generated by default as identity primary key,
  title text,
  category text,
  url text,
  username text,
  password text,
  pin text,
  two_factor text,
  phone text,
  fax text,
  account_number text,
  contact text,
  purpose text,
  notes text,
  password_changed_on date,
  status text not null default 'Active',
  locked boolean not null default false,
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null,
  archived_at timestamptz,
  deleted_at timestamptz
);
comment on table public.credentials is 'Logins & passwords — the office''s shared logins (shopping sites, Apple IDs, suppliers, software); secrets encrypted (F30)';
comment on column public.credentials.title is 'Site / service';
comment on column public.credentials.category is 'Category';
comment on column public.credentials.url is 'Address';
comment on column public.credentials.username is 'Username / email';
comment on column public.credentials.password is 'Password (encrypted)';
comment on column public.credentials.pin is 'PIN / security answer (encrypted)';
comment on column public.credentials.two_factor is '2FA / where the code goes';
comment on column public.credentials.account_number is 'Account #';
comment on column public.credentials.purpose is 'Used for';
comment on column public.credentials.password_changed_on is 'Password last changed';
create index on public.credentials (category);

insert into app.record_types (table_name, label, module, resource, parent_table, parent_column, lock_resource, sensitive_columns)
values ('credentials', 'Logins & passwords', 'administrative', 'credentials', null, null, null, '{password,pin}');

create trigger before_write before insert or update on public.credentials for each row execute function app.record_before_write();
create trigger audit after insert or update on public.credentials for each row execute function app.record_audit();

alter table public.credentials enable row level security;
create policy "view" on public.credentials for select to authenticated using ((select app.can_view_all('credentials')) or (created_by = (select auth.uid()) and (select app.can_view_page('credentials'))));
create policy "create" on public.credentials for insert to authenticated with check ((select app.can_do('credentials', 'create')));
create policy "modify" on public.credentials for update to authenticated using (((select app.can_view_all('credentials')) or (created_by = (select auth.uid()) and (select app.can_view_page('credentials')))) and ((select app.can_do('credentials', 'modify')) or (select app.can_do('credentials', 'delete')) or (select app.can_do('credentials', 'archive')))) with check (((select app.can_do('credentials', 'modify')) or (select app.can_do('credentials', 'delete')) or (select app.can_do('credentials', 'archive'))));

-- Who revealed or copied a secret, and when (any table with sensitive fields: logins, project credentials…).
create table public.sensitive_reveals (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id bigint not null,
  field text not null,
  action text not null default 'show' check (action in ('show', 'copy')),
  user_id uuid not null references public.profiles (id) on delete cascade,
  at timestamptz not null default now()
);
comment on table public.sensitive_reveals is 'F30: who revealed or copied a masked value (password, PIN, SSN…) and when';
create index on public.sensitive_reveals (table_name, record_id, at desc);
alter table public.sensitive_reveals enable row level security;
-- Everyone logs only in their own name; the log of a record is read by whoever may change that record.
create policy "log own" on public.sensitive_reveals for insert to authenticated with check (user_id = (select auth.uid()));
create policy "view" on public.sensitive_reveals for select to authenticated using ((select app.can_do(table_name, 'modify')) and app.record_visible(table_name, record_id));

