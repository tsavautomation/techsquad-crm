-- F26-2 Gmail intake (SPEC §9.1 F26-a, Fred 2026-10-21): the team forwards project emails to the CRM's
-- free Gmail account (tsavcrm@gmail.com). Every five minutes the CRM reads the mailbox, matches each
-- email to a project (#id or the project name in the subject, the sender against the project's
-- contacts, the thread) and files it as a project_events row (channel 'email'); attachments go to
-- OneDrive under <project> (<id>) › Email › <date> <subject>. Emails that match nothing wait in the
-- Assign list on Today. The connection (tokens, encrypted) lives in app_integrations under 'gmail'.

create table public.mail_messages (
  id bigint generated by default as identity primary key,
  gmail_id text not null unique,
  thread_id text,
  received_at timestamptz not null,
  from_name text,
  from_email text,
  to_text text,
  subject text,
  snippet text,
  body_text text,
  -- Forwarded mails: the addresses found in "From:" lines inside the body (the original senders).
  inner_senders text[] not null default '{}',
  -- [{ name, mime, size, attachment_id, item_id?, error? }]: Gmail parts, and the OneDrive item once filed.
  attachments jsonb not null default '[]',
  project_id bigint references public.projects (id) on delete set null,
  -- id | thread | subject | sender | manual
  matched_by text,
  status text not null default 'unassigned' check (status in ('unassigned', 'assigned', 'ignored')),
  event_id bigint references public.project_events (id) on delete set null,
  filed_at timestamptz,
  file_error text,
  assigned_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
comment on table public.mail_messages is 'Emails read from the CRM Gmail mailbox (F26-2): matched to a project and filed as project_events, or waiting in the Assign list';
create index on public.mail_messages (status) where status = 'unassigned';
create index on public.mail_messages (thread_id);
create index on public.mail_messages (project_id, received_at desc);

-- Written by the sync (service role). The office (everyone who sees all projects) reads the Assign list.
alter table public.mail_messages enable row level security;
create policy "office view" on public.mail_messages for select to authenticated
  using ((select app.has_permission('projects.projects.view_all')));

-- Every five minutes: the mailbox check. Same Vault secrets as crm-tick; the URL is the tick's with /mail.
select cron.schedule(
  'crm-mail',
  '*/5 * * * *',
  $$
  select net.http_get(
    url := replace((select decrypted_secret from vault.decrypted_secrets where name = 'crm_cron_url'), '/tick', '/mail'),
    headers := jsonb_build_object('Authorization', 'Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name = 'crm_cron_secret')),
    timeout_milliseconds := 30000
  )
  where exists (select 1 from vault.decrypted_secrets where name = 'crm_cron_url')
    and exists (select 1 from vault.decrypted_secrets where name = 'crm_cron_secret');
  $$
);
