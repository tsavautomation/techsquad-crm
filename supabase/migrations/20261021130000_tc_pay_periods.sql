-- TC-e / TC-f / TC-g Pay periods (SPEC §9.1, Jessica via Fred 2026-10-21, Stage 3): each employee has a pay
-- frequency; a period is computed (Biweekly from an anchor Monday, Semi-monthly 1–15 / 16–end, Monthly) and
-- only stored once the office approves and locks it, with one line per person (hours, PTO, rate, total).
-- Locked clock entries carry the period; an administrator may still correct one with a reason, and the
-- difference is paid as an adjustment in the next period. Only the Job costing permission may read any of
-- this (same rule as pay rates), and none of it ever goes to OneDrive (OD-e; src/lib/files/confidential.ts).

-- 1. Pay frequency on the employee (the form field; null = not in any pay period yet).
alter table public.employees add column pay_frequency text check (pay_frequency in ('Biweekly', 'Semi-monthly', 'Monthly'));
comment on column public.employees.pay_frequency is 'TC-e: Biweekly / Semi-monthly (1–15 and 16–end of month) / Monthly; null = not paid through pay periods';

-- 2. Approved (locked) periods.
create table public.pay_periods (
  id bigint generated by default as identity primary key,
  frequency text not null check (frequency in ('Biweekly', 'Semi-monthly', 'Monthly')),
  starts_on date not null,
  ends_on date not null,
  pay_day date not null,
  approved_by uuid references public.profiles (id) on delete set null,
  approved_at timestamptz not null default now(),
  note text,
  created_at timestamptz not null default now(),
  unique (frequency, starts_on)
);
comment on table public.pay_periods is 'TC-f: a pay period once approved and locked; open periods are computed, never stored';

create table public.pay_period_lines (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.pay_periods (id) on delete cascade,
  employee_id bigint not null references public.employees (id) on delete cascade,
  minutes integer not null default 0,
  pto_minutes integer not null default 0,
  rate_text text,
  amount numeric(12,2),
  adjustments numeric(12,2) not null default 0,
  flagged integer not null default 0,
  unique (period_id, employee_id)
);
comment on table public.pay_period_lines is 'TC-f: one person in a locked period: worked minutes, paid PTO minutes, the rate(s) used, hours × rate, and the earlier periods'' adjustments paid in this one';

create table public.pay_period_adjustments (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.pay_periods (id) on delete cascade,
  employee_id bigint not null references public.employees (id) on delete cascade,
  entry_id bigint references public.time_entries (id) on delete set null,
  reason text not null,
  delta_minutes integer not null default 0,
  delta_amount numeric(12,2),
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  applied_period_id bigint references public.pay_periods (id) on delete set null
);
create index on public.pay_period_adjustments (employee_id) where applied_period_id is null;
comment on table public.pay_period_adjustments is 'TC-f: an administrator''s correction of a locked entry, with the reason and the difference; applied_period_id = the later period that paid it';

-- 3. Locked clock entries carry their period.
alter table public.time_entries add column pay_period_id bigint references public.pay_periods (id) on delete set null;
create index on public.time_entries (pay_period_id) where pay_period_id is not null;
comment on column public.time_entries.pay_period_id is 'TC-f: set when the period was approved; only an administrator may change the entry after that (with a reason)';

-- A locked entry is changed only by an administrator (the app asks for the reason and records the adjustment).
create or replace function public.guard_locked_time_entry()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if old.pay_period_id is not null and not app.is_sysadmin() and coalesce(current_setting('app.engine', true), 'off') <> 'on' then
    raise exception 'This entry belongs to an approved pay period; only an administrator can change it' using errcode = '42501';
  end if;
  return coalesce(new, old);
end;
$$;
create trigger time_entries_locked before update or delete on public.time_entries
  for each row execute function public.guard_locked_time_entry();

-- 4. Only the Job costing permission reads or writes pay periods (same rule as employee_pay_rates).
alter table public.pay_periods enable row level security;
alter table public.pay_period_lines enable row level security;
alter table public.pay_period_adjustments enable row level security;
create policy "job costing manages pay periods" on public.pay_periods for all to authenticated
  using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
create policy "job costing manages pay period lines" on public.pay_period_lines for all to authenticated
  using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
create policy "job costing manages pay adjustments" on public.pay_period_adjustments for all to authenticated
  using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
grant select, insert, update, delete on public.pay_periods, public.pay_period_lines, public.pay_period_adjustments to authenticated;

-- 5. Settings: the biweekly anchor (a Monday) and the pay day as days after the period ends, per frequency.
insert into public.app_settings (key, value)
values ('payroll', '{"biweekly_anchor": "2026-10-05", "days_after": {"Biweekly": 5, "Semi-monthly": 5, "Monthly": 5}}')
on conflict (key) do nothing;
