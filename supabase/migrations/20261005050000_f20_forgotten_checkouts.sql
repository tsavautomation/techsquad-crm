values ('field_day', jsonb_build_object('time_clock', jsonb_build_object('auto_checkout', jsonb_build_object('time', '16:00', 'late_time', '17:00', 'late_employee_ids', jsonb_build_array(1004, 1005, 1006, 1012)))))
on conflict (key) do update
  set value = public.app_settings.value || jsonb_build_object(
    'time_clock',
    coalesce(public.app_settings.value -> 'time_clock', '{}'::jsonb) || jsonb_build_object('auto_checkout', jsonb_build_object('time', '16:00', 'late_time', '17:00', 'late_employee_ids', jsonb_build_array(1004, 1005, 1006, 1012)))
  );
