-- F26-1 Project timeline, project requests and shared alerts (SPEC §9.1 F26-a / F26-c, Fred 2026-10-21).
--
--   project_events    one stream per project for what does not live in a record of its own today
--                     (emails from F26-2, WhatsApp pastes, …); the Timeline card reads it next to the
--                     visits, reports, notes, status changes, tasks and requests the CRM already keeps.
--   project_requests  a line on the project: an RFI, a change order or another ask, Open until someone
--                     marks it Done (who and when are kept by a trigger, so the form and the button agree).
--   alert_acks        who read, acknowledged or cleared a shared alert and when. One "cleared" row hides
--                     the alert for everyone; "acknowledged" hides it for that person only.
--   app_settings 'shared_alerts'  who gets the request alerts (Saulo, Jessica, Lucas, Luana, Fred).

-- ---------------------------------------------------------------- 1. project events
create table public.project_events (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  channel text not null check (channel in ('email', 'whatsapp', 'call', 'note', 'request', 'other')),
  occurred_at timestamptz not null default now(),
  -- Who it came from, as text (an email sender, a WhatsApp name); actor_user when it was someone with a login.
  actor text,
  actor_user uuid references public.profiles (id) on delete set null,
  title text not null,
  body text,
  -- The record this event came from (a request line, later an email row), and an external reference (Gmail message id).
  source_table text,
  source_id bigint,
  source_ref text,
  -- [{ name, url, provider_path }]: files linked from the timeline (OneDrive in F26-2).
  attachments jsonb not null default '[]',
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  deleted_at timestamptz
);
comment on table public.project_events is 'Project timeline events that have no record of their own: emails, WhatsApp pastes, request notes (F26)';
create index on public.project_events (project_id, occurred_at desc);
create unique index project_events_source_ref_key on public.project_events (channel, source_ref) where source_ref is not null;

alter table public.project_events enable row level security;
-- Whoever sees the project sees its events; adding one counts as modifying the project. Engines use the service role.
create policy "view" on public.project_events for select to authenticated
  using (deleted_at is null and exists (select 1 from public.projects p where p.id = project_id));
create policy "add" on public.project_events for insert to authenticated
  with check ((select app.can_do('projects', 'modify')) and exists (select 1 from public.projects p where p.id = project_id));
create policy "remove own" on public.project_events for update to authenticated
  using (created_by = (select auth.uid()) and (select app.can_do('projects', 'modify')))
  with check (created_by = (select auth.uid()));

-- ---------------------------------------------------------------- 2. project requests (a sub-list of the project)
create table public.project_requests (
  id bigint generated by default as identity primary key,
  title text,
  project_id bigint not null references public.projects (id) on delete cascade,
  date date not null default ((now() at time zone 'America/New_York')::date),
  type text not null default 'RFI',
  description text,
  source_event_id bigint references public.project_events (id) on delete set null,
  status text not null default 'Open',
  closed_by uuid references public.profiles (id) on delete set null,
  closed_at timestamptz,
  locked boolean not null default false,
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null,
  archived_at timestamptz,
  deleted_at timestamptz
);
comment on table public.project_requests is 'Project Requests — an RFI, change order or other ask on a project, Open until marked Done (F26)';
comment on column public.project_requests.date is 'Date';
comment on column public.project_requests.type is 'Type';
comment on column public.project_requests.description is 'Description';
comment on column public.project_requests.source_event_id is 'From the timeline event';
comment on column public.project_requests.status is 'Status';
comment on column public.project_requests.closed_by is 'Closed by';
comment on column public.project_requests.closed_at is 'Closed at';
create index on public.project_requests (project_id, date desc);
create index on public.project_requests (status) where status = 'Open';

insert into app.record_types (table_name, label, module, resource, parent_table, parent_column, lock_resource, sensitive_columns) values
  ('project_requests', 'Project Requests', 'projects', null, 'projects', 'project_id', null, '{}');

-- Done ⇒ who closed it and when; back to Open clears both. Runs before the audit trigger, so the log shows them.
create or replace function app.project_request_close()
returns trigger
language plpgsql security invoker set search_path = ''
as $$
begin
  if new.status = 'Done' and (tg_op = 'INSERT' or old.status is distinct from 'Done') then
    new.closed_at := now();
    new.closed_by := coalesce(auth.uid(), new.updated_by);
  elsif new.status <> 'Done' then
    new.closed_at := null;
    new.closed_by := null;
  end if;
  return new;
end;
$$;

create trigger before_write before insert or update on public.project_requests for each row execute function app.record_before_write();
create trigger close_request before insert or update on public.project_requests for each row execute function app.project_request_close();
create trigger audit after insert or update on public.project_requests for each row execute function app.record_audit();

alter table public.project_requests enable row level security;
create policy "view" on public.project_requests for select to authenticated
  using (exists (select 1 from public.projects p where p.id = project_id));
create policy "create" on public.project_requests for insert to authenticated
  with check (exists (select 1 from public.projects p where p.id = project_id) and (select app.can_do('project_requests', 'create')));
create policy "modify" on public.project_requests for update to authenticated
  using (exists (select 1 from public.projects p where p.id = project_id) and (select app.can_do('project_requests', 'modify')))
  with check (exists (select 1 from public.projects p where p.id = project_id));

-- ---------------------------------------------------------------- 3. shared alerts: the acknowledgement log
create table public.alert_acks (
  id bigint generated by default as identity primary key,
  -- What the alert is about: 'project_request' + the request id today; other kinds later.
  kind text not null,
  ref_id bigint not null,
  user_id uuid not null references public.profiles (id) on delete cascade,
  action text not null check (action in ('read', 'acknowledged', 'cleared')),
  at timestamptz not null default now()
);
comment on table public.alert_acks is 'Shared alerts: who read, acknowledged or cleared each alert and when (F26-c). A "cleared" row clears it for everyone.';
-- One row per person and action: logging again is a no-op (on conflict do nothing).
create unique index alert_acks_once on public.alert_acks (kind, ref_id, user_id, action);
create index on public.alert_acks (kind, ref_id);

alter table public.alert_acks enable row level security;
-- Staff who may open projects see the log; everyone logs only in their own name. Nothing is ever edited or removed.
create policy "view" on public.alert_acks for select to authenticated
  using ((select app.has_permission('projects.projects.view_page')));
create policy "log own" on public.alert_acks for insert to authenticated
  with check (user_id = (select auth.uid()) and (select app.has_permission('projects.projects.view_page')));

