-- TC-h Weekly timesheet approval (SPEC §9.1, Jessica via Fred 2026-10-29, item 1): the office approves each
-- person's week (Monday to Sunday) once it has ended and nothing is left to look at. An approved week is
-- locked: no clock entry of that person in that week can be added, moved or removed until someone with the
-- "Approve / reopen timesheets" permission reopens it with a reason. A week without a row is Open.
--
-- Stage 3's pay-period lock (TC-f) stays as it is: the week approval is the office's step before it.

create table public.timesheet_weeks (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  monday date not null check (extract(isodow from monday) = 1),
  status text not null check (status in ('Approved', 'Reopened')),
  minutes_at_approval integer,
  approved_by uuid references public.profiles (id) on delete set null,
  approved_at timestamptz,
  reopened_by uuid references public.profiles (id) on delete set null,
  reopened_at timestamptz,
  reopen_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id, monday)
);
comment on table public.timesheet_weeks is 'TC-h: one person''s week once approved (locked) or reopened; no row = Open';

-- Every approval and reopening, for the record.
create table public.timesheet_week_events (
  id bigint generated by default as identity primary key,
  week_id bigint not null references public.timesheet_weeks (id) on delete cascade,
  action text not null check (action in ('approved', 'reopened')),
  minutes integer,
  reason text,
  by_user uuid references public.profiles (id) on delete set null,
  at timestamptz not null default now()
);
create index on public.timesheet_week_events (week_id);
comment on table public.timesheet_week_events is 'TC-h: who approved or reopened a week, when, and why';

