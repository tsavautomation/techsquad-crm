-- The Monday (Eastern) of the week an instant belongs to; the same rule the timesheets use.
create or replace function public.timesheet_monday(p_at timestamptz)
returns date
language sql stable
set search_path = ''
as $$
  select date_trunc('week', (p_at at time zone 'America/New_York'))::date
$$;

create or replace function public.timesheet_week_approved(p_employee bigint, p_at timestamptz)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.timesheet_weeks w
    where w.employee_id = p_employee and w.status = 'Approved' and w.monday = public.timesheet_monday(p_at)
  )
$$;

-- The lock. Keeps TC-f's rule (an entry in an approved pay period: administrators only) and adds the week:
-- an entry whose person + week is approved cannot be added, moved to another time, removed or restored
-- by anyone (the engine excepted); the office reopens the week first. Marks such as "reviewed" still pass.
create or replace function public.guard_locked_time_entry()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  engine boolean := coalesce(current_setting('app.engine', true), 'off') = 'on';
  moved boolean;
begin
  if tg_op = 'INSERT' then
    if not engine and public.timesheet_week_approved(new.employee_id, new.at) then
      raise exception 'This week''s timesheet is approved; reopen it on Timesheets before adding an entry' using errcode = '42501';
    end if;
    return new;
  end if;
  if old.pay_period_id is not null and not app.is_sysadmin() and not engine then
    raise exception 'This entry belongs to an approved pay period; only an administrator can change it' using errcode = '42501';
  end if;
  moved := tg_op = 'DELETE'
    or new.at is distinct from old.at
    or new.kind is distinct from old.kind
    or new.employee_id is distinct from old.employee_id
    or new.deleted_at is distinct from old.deleted_at;
  if moved and not engine and (
    public.timesheet_week_approved(old.employee_id, old.at)
    or (tg_op = 'UPDATE' and public.timesheet_week_approved(new.employee_id, new.at))
  ) then
    raise exception 'This week''s timesheet is approved; reopen it on Timesheets before changing an entry' using errcode = '42501';
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists time_entries_locked on public.time_entries;
create trigger time_entries_locked before insert or update or delete on public.time_entries
  for each row execute function public.guard_locked_time_entry();

