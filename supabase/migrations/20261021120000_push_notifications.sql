-- F27 Push notifications (Fred 2026-10-21, "push notifications when any technician clocks in / out of
-- any job, toggled on or off, for now only on Jessica, Saulo and Fred's logins").
--
-- profiles.push_events: which events reach this login (set by an administrator on Admin › Users).
-- push_subscriptions: one row per browser / phone that allowed notifications (Web Push endpoint).
-- push_log: every notification sent or failed, for the record.

alter table public.profiles add column if not exists push_events text[] not null default '{}';
comment on column public.profiles.push_events is 'F27: push notification events this login receives (visit_check_in, visit_check_out)';

create table public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  failed_at timestamptz
);
create index push_subscriptions_user_idx on public.push_subscriptions (user_id);
alter table public.push_subscriptions enable row level security;
create policy "own subscriptions" on public.push_subscriptions for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create table public.push_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  kind text not null,
  title text not null,
  body text,
  url text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  error text
);
create index push_log_user_idx on public.push_log (user_id, created_at desc);
alter table public.push_log enable row level security;
create policy "own log" on public.push_log for select to authenticated using (user_id = (select auth.uid()));

-- The first three logins (Fred 2026-10-21).
update public.profiles set push_events = array['visit_check_in', 'visit_check_out']
where email in ('fred@tsav.net', 'jessica@tsav.net', 'saulo@tsav.net');
