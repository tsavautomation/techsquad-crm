-- ---------------------------------------------------------------- engine helpers (service role only)

-- Every real table in public with its primary-key columns (comma-separated, '' when it has none).
create or replace function public.backup_tables()
returns table (table_name text, pk text)
language sql stable security definer set search_path = ''
as $$
  select c.relname::text,
         coalesce((select string_agg(a.attname, ',' order by array_position(i.indkey, a.attnum))
                     from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
                    where i.indrelid = c.oid and i.indisprimary), '') as pk
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p')
   order by 1;
$$;

-- Put rows back exactly as they were: triggers off for the duration (timestamps, authors and locks come from the
-- copy, nothing is re-audited or re-triggered), insert or overwrite by primary key. Columns the table no longer has
-- are ignored; columns added since are left null / default. Generated columns are skipped.
create or replace function public.restore_rows(p_table text, p_rows jsonb)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  pk text;
  cols text;
  sets text;
  n integer;
begin
  if p_table !~ '^[a-z_][a-z0-9_]*$' then raise exception 'bad table name'; end if;
  select string_agg(quote_ident(a.attname), ', ' order by array_position(i.indkey, a.attnum)) into pk
    from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
   where i.indrelid = ('public.' || quote_ident(p_table))::regclass and i.indisprimary;
  if pk is null then raise exception 'table % has no primary key', p_table; end if;
  select string_agg(quote_ident(attname), ', ' order by attnum),
         string_agg(quote_ident(attname) || ' = excluded.' || quote_ident(attname), ', ' order by attnum) filter (where not (attname = any (string_to_array(replace(pk, '"', ''), ', '))))
    into cols, sets
    from pg_attribute
   where attrelid = ('public.' || quote_ident(p_table))::regclass and attnum > 0 and not attisdropped and attgenerated = '';
  execute format('alter table public.%I disable trigger user', p_table);
  if sets is null then
    execute format('insert into public.%1$I (%2$s) select %2$s from jsonb_populate_recordset(null::public.%1$I, $1) on conflict (%3$s) do nothing', p_table, cols, pk) using p_rows;
  else
    execute format('insert into public.%1$I (%2$s) select %2$s from jsonb_populate_recordset(null::public.%1$I, $1) on conflict (%3$s) do update set %4$s', p_table, cols, pk, sets) using p_rows;
  end if;
  get diagnostics n = row_count;
  execute format('alter table public.%I enable trigger user', p_table);
  return n;
end;
$$;

-- "Also delete records added after that night": everything whose id is not in the copy.
create or replace function public.restore_delete_missing(p_table text, p_ids bigint[])
returns integer
language plpgsql security definer set search_path = ''
as $$
declare n integer;
begin
  if p_table !~ '^[a-z_][a-z0-9_]*$' then raise exception 'bad table name'; end if;
  execute format('alter table public.%I disable trigger user', p_table);
  execute format('delete from public.%I where id <> all($1)', p_table) using p_ids;
  get diagnostics n = row_count;
  execute format('alter table public.%I enable trigger user', p_table);
  return n;
end;
$$;

-- After a restore the id counter must sit past the highest id again.
create or replace function public.restore_fix_sequence(p_table text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare seq text;
begin
  if p_table !~ '^[a-z_][a-z0-9_]*$' then raise exception 'bad table name'; end if;
  seq := pg_get_serial_sequence('public.' || quote_ident(p_table), 'id');
  if seq is not null then
    execute format('select setval(%L, greatest(coalesce((select max(id) from public.%I), 0), 1000) + 1, false)', seq, p_table);
  end if;
end;
$$;

revoke execute on function public.backup_tables(), public.restore_rows(text, jsonb), public.restore_delete_missing(text, bigint[]), public.restore_fix_sequence(text) from public, anon, authenticated;
grant execute on function public.backup_tables(), public.restore_rows(text, jsonb), public.restore_delete_missing(text, bigint[]), public.restore_fix_sequence(text) to service_role;
