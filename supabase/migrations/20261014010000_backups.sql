-- BK-a Backups (SPEC §9.1 BK-a, Fred 2026-10-14): every night the CRM writes a copy of every table to OneDrive
-- (TechSquad CRM / Backups / <date> / <table>.json.gz + <table>.csv), keeps 30 days, and lets the restore list
-- (Fred) put a table back as it was on one of those nights. Jessica, Luana, Saulo and Lucas see the list.

create table public.backups (
  id bigint generated by default as identity primary key,
  day date not null,
  kind text not null default 'nightly' check (kind in ('nightly', 'manual', 'before_restore')),
  status text not null default 'running' check (status in ('running', 'done', 'failed', 'expired')),
  folder_path text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  lease_until timestamptz,
  tables jsonb not null default '[]',
  bytes bigint not null default 0,
  rows_total bigint not null default 0,
  error text,
  started_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index backups_nightly_day_key on public.backups (day) where kind = 'nightly';
comment on table public.backups is 'BK-a: one row per backup run; tables = [{name, rows, bytes, json_id, csv_id}]; expired once its OneDrive folder was removed after the retention period.';

create table public.backup_restores (
  id bigint generated by default as identity primary key,
  backup_id bigint not null references public.backups (id) on delete cascade,
  table_name text not null,
  rows_written integer not null default 0,
  rows_deleted integer not null default 0,
  snapshot_backup_id bigint references public.backups (id) on delete set null,
  error text,
  restored_by uuid references public.profiles (id) on delete set null,
  restored_at timestamptz not null default now()
);
comment on table public.backup_restores is 'BK-a: every restore: who, which table, how many rows, and the safety copy taken first.';

alter table public.backups enable row level security;
alter table public.backup_restores enable row level security;
create policy "backup viewers read" on public.backups for select to authenticated using (app.has_permission('backups.page.view'));
create policy "backup viewers read restores" on public.backup_restores for select to authenticated using (app.has_permission('backups.page.view'));
grant select on public.backups, public.backup_restores to authenticated;

