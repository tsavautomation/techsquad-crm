-- F28-b WhatsApp conversations (Fred 2026-10-21, "we can't receive 30 entries on the CRM"): one card per conversation,
-- not per message. Messages of the same chat gather on an open conversation; Claude re-reads the thread after a
-- quiet period and updates the card. A conversation can be assigned to a project, and then lives on the project's
-- timeline as one event (channel 'whatsapp') that follows the card.

create table public.wa_conversations (
  id bigint generated by default as identity primary key,
  source text not null default 'whatsapp',
  chat text not null,
  project_id bigint references public.projects (id) on delete set null,
  event_id bigint references public.project_events (id) on delete set null,
  started_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  message_count integer not null default 0,
  -- AI reading: pending until the thread has been quiet; read_through = the last message id Claude saw.
  ai_pending boolean not null default true,
  ai_at timestamptz,
  read_through bigint,
  category text not null default 'fyi' check (category in ('service_call', 'follow_up', 'quote', 'scheduling', 'fyi')),
  priority text not null default 'normal' check (priority in ('urgent', 'normal', 'low')),
  customer text,
  phone text,
  system text,
  summary text not null default '',
  details text,
  status text not null default 'open' check (status in ('open', 'in_progress', 'done', 'dismissed')),
  assigned_to text,
  triage text not null default 'fallback' check (triage in ('ai', 'fallback')),
  triage_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.wa_conversations is 'F28-b: one WhatsApp conversation per chat and subject, read by Claude, worked on /whatsapp, optionally on a project timeline';
create index wa_conversations_chat_idx on public.wa_conversations (chat, status, last_message_at desc);
create index wa_conversations_last_idx on public.wa_conversations (last_message_at desc);
create index wa_conversations_pending_idx on public.wa_conversations (ai_pending, last_message_at) where ai_pending;
create index wa_conversations_project_idx on public.wa_conversations (project_id) where project_id is not null;
create trigger wa_conversations_touch before update on public.wa_conversations
  for each row execute function app.touch_updated_at();

alter table public.wa_messages add column conversation_id bigint references public.wa_conversations (id) on delete set null;
create index wa_messages_conversation_idx on public.wa_messages (conversation_id, id);

-- The cards filed so far (one per message) become one conversation each; their messages follow.
insert into public.wa_conversations (chat, started_at, last_message_at, message_count, ai_pending, ai_at, read_through, category, priority, customer, phone, system, summary, details, status, assigned_to, triage, triage_error, created_at)
select t.chat, t.occurred_at, t.occurred_at, 1, false, t.created_at, t.message_id, t.category, t.priority, t.customer, t.phone, t.system, t.summary, t.details, t.status, t.assigned_to, t.triage, t.triage_error, t.created_at
from public.wa_tasks t order by t.id;
update public.wa_messages m set conversation_id = c.id
from public.wa_conversations c where c.read_through = m.id and m.conversation_id is null;
drop table public.wa_tasks;

alter table public.wa_conversations enable row level security;
create policy "whatsapp read conversations" on public.wa_conversations for select to authenticated
  using ((select app.has_permission('whatsapp.page.view')));
create policy "whatsapp work conversations" on public.wa_conversations for update to authenticated
  using ((select app.has_permission('whatsapp.page.view')))
  with check ((select app.has_permission('whatsapp.page.view')));

update public.automations set table_name = 'wa_conversations', title = 'AI reading of WhatsApp conversations',
  notes = 'F28-b: after a conversation has been quiet for two minutes, Claude reads the thread and updates its card on the WhatsApp board (service call, follow-up, quote, scheduling or FYI; urgent, normal or low). A new subject in the same chat starts a new card.'
where id = 900503;
