-- OT Overtime (Fred 2026-11-05 spec, after Part 4): overtime rate per person, daily regular hours per time-clock
-- group (with a per-person override), work trips with a premium %, and the split of each locked line.

-- 1. Overtime rate per person: $/h typed by hand, with history, like the pay rate. Never derived from the pay rate.
create table public.employee_overtime_rates (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  hourly_rate numeric(12,2) not null check (hourly_rate >= 0),
  effective_from date not null default (now() at time zone 'America/New_York')::date,
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  unique (employee_id, effective_from)
);
create index on public.employee_overtime_rates (employee_id, effective_from desc);
comment on table public.employee_overtime_rates is 'OT: overtime rate ($/h) per employee with history; the value in force on the day worked pays the hours over the daily limit; only job_costing.view may read or write';
alter table public.employee_overtime_rates enable row level security;
create policy "job costing reads overtime rates" on public.employee_overtime_rates for select to authenticated using (app.has_permission('job_costing.view'));
create policy "job costing adds overtime rates" on public.employee_overtime_rates for insert to authenticated with check (app.has_permission('job_costing.view'));
create policy "job costing changes overtime rates" on public.employee_overtime_rates for update to authenticated using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
create policy "job costing removes overtime rates" on public.employee_overtime_rates for delete to authenticated using (app.has_permission('job_costing.view'));
grant select, insert, update, delete on public.employee_overtime_rates to authenticated;

-- 2. Daily regular hours per time-clock group, with history (the value in force on the day worked). Office 10 h, Field 9 h to start.
