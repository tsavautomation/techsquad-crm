);
comment on table public.clock_group_hours is 'OT: regular hours per day (and optionally per week) of each time-clock group, with history; the hours of a day past the limit are overtime';
alter table public.clock_group_hours enable row level security;
create policy "staff read group hours" on public.clock_group_hours for select to authenticated using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "job costing adds group hours" on public.clock_group_hours for insert to authenticated with check (app.has_permission('job_costing.view'));
create policy "job costing changes group hours" on public.clock_group_hours for update to authenticated using (app.has_permission('job_costing.view')) with check (app.has_permission('job_costing.view'));
create policy "job costing removes group hours" on public.clock_group_hours for delete to authenticated using (app.has_permission('job_costing.view'));
grant select, insert, update, delete on public.clock_group_hours to authenticated;
insert into public.clock_group_hours (clock_group, daily_minutes, effective_from, note) values ('Field', 540, '2000-01-01', 'Initial value'), ('Office', 600, '2000-01-01', 'Initial value');

