-- 4. Work trips: a premium % on every hour (regular and overtime) of the days inside, per person; no overlap.
create extension if not exists btree_gist with schema extensions;
create table public.work_trips (
  id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  starts_on date not null,
  ends_on date not null check (ends_on >= starts_on),
  premium_pct numeric(5,2) not null check (premium_pct >= 0 and premium_pct <= 200),
  project_id bigint references public.projects (id) on delete set null,
  destination text,
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id) on delete set null,
  constraint work_trips_no_overlap exclude using gist (employee_id with =, daterange(starts_on, ends_on, '[]') with &&)
);
create index on public.work_trips (employee_id, starts_on);
comment on table public.work_trips is 'OT: a person''s work trip (both dates included) and the premium % added to every hour of those days; one trip at a time per person';
create trigger work_trips_touch before update on public.work_trips for each row execute function app.touch_updated_at();
alter table public.work_trips enable row level security;
create policy "staff read work trips" on public.work_trips for select to authenticated using (app.has_permission('administrative.employees.view_all') or app.has_permission('job_costing.view'));
create policy "office adds work trips" on public.work_trips for insert to authenticated with check (app.has_permission('administrative.employees.modify') or app.has_permission('job_costing.view'));
create policy "office changes work trips" on public.work_trips for update to authenticated using (app.has_permission('administrative.employees.modify') or app.has_permission('job_costing.view')) with check (app.has_permission('administrative.employees.modify') or app.has_permission('job_costing.view'));
create policy "office removes work trips" on public.work_trips for delete to authenticated using (app.has_permission('administrative.employees.modify') or app.has_permission('job_costing.view'));
grant select, insert, update, delete on public.work_trips to authenticated;

-- 5. A locked line keeps its split: regular / overtime minutes, the overtime rate(s) used and the trip premium paid.
alter table public.pay_period_lines
  add column regular_minutes integer not null default 0,
  add column overtime_minutes integer not null default 0,
  add column overtime_rate_text text,
  add column premium_amount numeric(12,2) not null default 0;
comment on column public.pay_period_lines.premium_amount is 'OT: the work-trip premium included in amount';
-- Lines locked before this change: everything was paid as regular.
update public.pay_period_lines set regular_minutes = minutes where regular_minutes = 0 and overtime_minutes = 0;
