-- F28-d Ignore rules (Fred 2026-10-22, "from the group TIME TS ignore check in / check out and all variations;
-- ignore all messages from Recibos TS"): a rule is a chat (or any chat) plus a text pattern; a message that
-- matches is stored flagged muted, makes no card and is never read. Managed on WhatsApp › Muted chats.

create table public.wa_ignore_rules (
  id bigint generated by default as identity primary key,
  chat text,                       -- null = every chat
  kind text not null default 'contains' check (kind in ('contains', 'regex')),
  pattern text not null,
  note text,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
comment on table public.wa_ignore_rules is 'F28-d: messages matching (chat, pattern) make no WhatsApp card';
alter table public.wa_ignore_rules enable row level security;
create policy "whatsapp read rules" on public.wa_ignore_rules for select to authenticated
  using ((select app.has_permission('whatsapp.page.view')));
create policy "whatsapp add rule" on public.wa_ignore_rules for insert to authenticated
  with check ((select app.has_permission('whatsapp.page.view')));
create policy "whatsapp drop rule" on public.wa_ignore_rules for delete to authenticated
  using ((select app.has_permission('whatsapp.page.view')));

-- TIME TS: "Checking warehouse", "Checkout warehouse", "Check in", "check-out", "checked in" and so on.
insert into public.wa_ignore_rules (chat, kind, pattern, note) values
('TIME TS', 'regex', '\mcheck(ing|ed|in|out|[\s/-]*(in|out))\M', 'Fred 2026-10-22: check in / check out and all variations');
-- Recibos TS: the whole group.
insert into public.wa_muted_chats (chat) values ('Recibos TS') on conflict (chat) do nothing;

-- Existing clutter: open Recibos TS cards, and TIME TS cards made only of check in / out messages.
update public.wa_conversations set status = 'dismissed', ai_pending = false
where status in ('open', 'in_progress') and (
  chat = 'Recibos TS'
  or (chat = 'TIME TS' and not exists (
    select 1 from public.wa_messages m where m.conversation_id = wa_conversations.id
      and m.body !~* '\mcheck(ing|ed|in|out|[\s/-]*(in|out))\M'))
);
