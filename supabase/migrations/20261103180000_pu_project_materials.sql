-- PU-a (Fred 2026-11-03): the project's materials pick list. One row per equipment / material line of the proposals
-- linked to the project (Part + CustomItem from Portal.io), plus lines people add by hand (consumables, things
-- outside the proposal). Each line is open (to buy, or in stock when the ledger has enough of that model),
-- purchased, replaced by another line, or removed. "In stock" is never stored: it is read from stock_levels every
-- time, so a line that was covered yesterday shows "to buy" again when the stock is gone. Nothing here moves stock.
-- Seen and edited by the people with Administrative › Purchasing (Finance and Transactions holders too).

create or replace function app.can_purchase()
returns boolean language sql stable security definer set search_path = ''
as $$
  select app.has_permission('administrative.purchasing.view_page') or app.has_permission('administrative.finance.view_page') or app.has_permission('administrative.transactions.view_page');
$$;
revoke execute on function app.can_purchase() from public, anon;
grant execute on function app.can_purchase() to authenticated;

create table public.project_materials (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  proposal_item_id bigint references public.proposal_items (id) on delete set null,
  product_id bigint references public.products (id) on delete set null,     -- picked by a person (replace / add); otherwise matched live by model
  brand text,
  model text,
  name text,
  quantity numeric(12,2) not null default 1,
  unit_cost numeric(12,2),
  status text not null default 'open' check (status in ('open', 'purchased', 'replaced', 'removed')),
  replaces_id bigint references public.project_materials (id) on delete set null, -- the line this one took the place of
  source text not null default 'portal' check (source in ('portal', 'manual')),
  edited boolean not null default false,                                     -- a person changed qty / cost: the Portal.io re-sync leaves them
  notes text,
  purchased_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null
);
comment on table public.project_materials is 'PU-a: the project''s materials pick list (proposal lines + hand-added lines) with what was bought, replaced or removed. In stock is computed from stock_levels on read.';
create unique index project_materials_item_key on public.project_materials (proposal_item_id) where proposal_item_id is not null;
create index on public.project_materials (project_id, status);
alter table public.project_materials enable row level security;
create policy "purchasers read" on public.project_materials for select to authenticated using ((select app.can_purchase()));
create policy "purchasers write" on public.project_materials for insert to authenticated with check ((select app.can_purchase()));
create policy "purchasers modify" on public.project_materials for update to authenticated using ((select app.can_purchase())) with check ((select app.can_purchase()));
grant select, insert, update on public.project_materials to authenticated;

-- Brings the pick list up to date with the proposals: a row for every buyable line that has none yet; the Portal.io
-- values (brand, model, name, qty, unit cost) refreshed on open lines nobody edited. Null = every project.
create or replace function public.sync_project_materials(p_project_id bigint default null)
returns integer language plpgsql security definer set search_path = ''
as $$
declare n integer;
begin
  if not app.can_purchase() then raise exception 'permission denied'; end if;
  with lines as (
    select i.id as item_id, t.project_id, i.brand, i.model, coalesce(i.name, i.description) as name, coalesce(i.quantity, 1) as quantity, i.cost
    from public.proposal_items i
    join public.transactions t on t.id = i.transaction_id and t.deleted_at is null and t.type = 'Proposal' and t.payment_type = 'Apply to Project' and t.project_id is not null
    where i.item_type in ('Part', 'CustomItem') and (p_project_id is null or t.project_id = p_project_id)
  ), upd as (
    update public.project_materials m
    set brand = l.brand, model = l.model, name = l.name, quantity = l.quantity, unit_cost = l.cost, updated_at = now()
    from lines l
    where m.proposal_item_id = l.item_id and m.status = 'open' and not m.edited
      and (m.brand is distinct from l.brand or m.model is distinct from l.model or m.name is distinct from l.name or m.quantity is distinct from l.quantity or m.unit_cost is distinct from l.cost)
  ), ins as (
    insert into public.project_materials (project_id, proposal_item_id, brand, model, name, quantity, unit_cost, source, created_by, updated_by)
    select l.project_id, l.item_id, l.brand, l.model, l.name, l.quantity, l.cost, 'portal', null, null
    from lines l
    where not exists (select 1 from public.project_materials m where m.proposal_item_id = l.item_id)
    returning 1
  )
  select count(*) into n from ins;
  return n;
end;
$$;
revoke execute on function public.sync_project_materials(bigint) from public, anon;
grant execute on function public.sync_project_materials(bigint) to authenticated;

-- The lines with their stock: the product (picked, or the first active product with the same model), on hand over
-- every location (stock_levels) and where. Status / year filters serve Administrative › Purchasing; a single
-- project serves its Materials card. Manual lines take the year they were added.
create or replace function public.project_materials_list(p_project_id bigint default null, p_statuses text[] default null, p_year integer default null)
returns table (
  id bigint, project_id bigint, project text, job_status text,
  proposal_item_id bigint, product_id bigint, product text, brand text, model text, name text,
  quantity numeric, unit_cost numeric, status text, replaces_id bigint, source text, edited boolean, notes text, purchased_at timestamptz,
  item_type text, supplier text, msrp numeric, sell_price numeric, proposal_number text,
  on_hand numeric, locations text
)
language sql stable security definer set search_path = ''
as $$
  select m.id, p.id, p.title, p.job_status,
         m.proposal_item_id, pr.id, pr.title, m.brand, m.model, m.name,
         m.quantity, m.unit_cost, m.status, m.replaces_id, m.source, m.edited, m.notes, m.purchased_at,
         coalesce(i.item_type, 'Part'), i.supplier, i.msrp, i.sell_price, t.portal_number,
         coalesce(s.on_hand, 0), s.locations
  from public.project_materials m
  join public.projects p on p.id = m.project_id and p.deleted_at is null
  left join public.proposal_items i on i.id = m.proposal_item_id
  left join public.transactions t on t.id = i.transaction_id
  left join lateral (
    select x.id, x.title from public.products x
    where x.deleted_at is null and x.archived_at is null
      and (x.id = m.product_id or (m.product_id is null and m.model is not null and lower(trim(x.model)) = lower(trim(m.model))))
    order by (x.id = m.product_id) desc, x.id
    limit 1
  ) pr on true
  left join lateral (
    select sum(l.on_hand) as on_hand, string_agg(l.location || ' ' || trim(to_char(l.on_hand, 'FM9999990.##')), ', ' order by l.on_hand desc) as locations
    from public.stock_levels l where l.product_id = pr.id and l.on_hand > 0
  ) s on true
  where (p_project_id is null or m.project_id = p_project_id)
    and (p_statuses is null or p.job_status = any (p_statuses))
    and (p_year is null or extract(year from coalesce(t.date, m.created_at::date)) = p_year)
    and (p_project_id is not null or p.category = 'Low Voltage')
    and app.can_purchase()
  order by p.title, m.id;
$$;
revoke execute on function public.project_materials_list(bigint, text[], integer) from public, anon;
grant execute on function public.project_materials_list(bigint, text[], integer) to authenticated;
