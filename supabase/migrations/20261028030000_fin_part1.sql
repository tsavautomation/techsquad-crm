-- FIN Part 1 (Fred 2026-10-28, SPEC §9.1 FIN-a…FIN-h): the Low Voltage finance module that replaces Luana's
-- "Sales Projections" spreadsheet. Transactions gain the payment, invoice and proposal details; the figures
-- (balance, P&L) come from project_financials v3; Financial Status is computed on read (no stored value, no
-- hourly automation); Payment Reliability lives on the paying client.

-- ---------------------------------------------------------------- Transactions
alter table public.transactions
  -- Payment
  add column method text,                       -- Credit Card / ACH / Zelle / Wire / Check / Cash / Other
  add column reference text,                    -- check number, confirmation, Stripe id…
  add column cc_fee numeric(12,2),              -- the portal's 3 % card fee, kept apart: never reduces the balance
  add column tip numeric(12,2),
  add column discount numeric(12,2),            -- reduces the balance like a payment, listed apart
  -- Invoice (= a Portal.io payment request / payment-schedule line)
  add column due_date date,
  add column due_date_edited_at timestamptz,    -- set when a person changes due_date; the sync then leaves it alone
  add column invoice_status text,               -- Draft / Submitted / Viewed / Paid / Declined (Portal.io's words)
  -- Approved Proposal
  add column is_change_order boolean not null default false,
  add column parent_transaction_id bigint references public.transactions (id) on delete set null,
  add column sales_tax numeric(12,2),
  add column parts_cost numeric(12,2),          -- Σ cost × quantity of Part + CustomItem lines (P&L Parts)
  -- Portal.io ids (the only keys the sync uses; the number stays informative)
  add column portal_proposal_id bigint,
  add column portal_change_order_id bigint,
  add column portal_request_id bigint;
comment on column public.transactions.cc_fee is 'FIN-a: card fee the portal charges on top; never part of Paid $';
comment on column public.transactions.due_date_edited_at is 'FIN-a: a person edited Due Date; the Portal.io sync never overwrites it';
create unique index transactions_portal_request_key on public.transactions (portal_request_id) where portal_request_id is not null and deleted_at is null;
create unique index transactions_portal_proposal_key on public.transactions (portal_proposal_id, coalesce(portal_change_order_id, 0)) where portal_proposal_id is not null and deleted_at is null;
create index transactions_parent_idx on public.transactions (parent_transaction_id);
create index transactions_due_idx on public.transactions (project_id, type, due_date);

-- A person's edit of Due Date is remembered (the service role, i.e. the sync, has no auth.uid()).
create or replace function app.transactions_due_date_edit()
returns trigger language plpgsql set search_path = '' as $$
begin
  if auth.uid() is not null and new.due_date is distinct from old.due_date then
    new.due_date_edited_at := now();
  end if;
  return new;
end $$;
create trigger transactions_due_date_edit before update on public.transactions
  for each row execute function app.transactions_due_date_edit();

-- Items of an Approved Proposal (from Portal.io): Parts for the P&L now, job costing later.
create table public.proposal_items (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.transactions (id) on delete cascade,
  portal_item_id bigint,
  item_type text,                               -- Part / Labor / CustomItem / Fee
  brand text,
  model text,
  name text,
  description text,
  quantity numeric(12,2),
  cost numeric(12,2),                           -- unit cost (null when Portal.io hides costs)
  sell_price numeric(12,2),                     -- unit sell price
  total numeric(12,2),                          -- line total before tax
  supplier text,
  created_at timestamptz not null default now()
);
comment on table public.proposal_items is 'FIN-e: the lines of an Approved Proposal as Portal.io sent them; Parts = Σ cost × quantity of Part + CustomItem';
create unique index proposal_items_portal_key on public.proposal_items (transaction_id, portal_item_id) where portal_item_id is not null;
alter table public.proposal_items enable row level security;
create policy "proposal items read" on public.proposal_items for select to authenticated
  using ((select app.has_permission('administrative.transactions.view_page')) or (select app.has_permission('administrative.finance.view_page')) or (select app.has_permission('job_costing.view')));

