-- FIN-m (Fred 2026-10-28): Luana's "Sales Projections" sheet (973 proposals 2022-2026, with the payments typed by
-- month) is imported into a staging table and offered for review exactly like Portal.io proposals: Link to project,
-- New project, Ignore. Linking writes the Approved Proposal and the monthly Payments under the project.

create table public.sheet_proposals (
  id bigint generated by default as identity primary key,
  number text,                                   -- the sheet's Invoice column: Portal.io proposal number (2732, 2357CO1) or a quote (Q8178388, SC0247)
  main_number integer,                           -- the digits of the Portal.io number (2357 for 2357CO1), to match the mirror
  change_order integer,                          -- n of <main>CO<n>
  year integer,
  date date,
  customer text,
  designer text,
  commission boolean not null default false,     -- the sheet's "Y"
  title text,
  amount numeric(12,2),
  payments jsonb not null default '[]'::jsonb,   -- [{month: '2024-01', amount}], month '2023' = the lump of that year
  discount numeric(12,2),
  cc_fee numeric(12,2),
  tip numeric(12,2),
  commission_amount numeric(12,2),
  status text,                                   -- Completed / In Progress / On Hold
  receivable text,                               -- Paid / In Progress / Overdue (the sheet's own word; the CRM computes its own)
  probability text,                              -- HIGH / MEDIUM / LOW → Payment Reliability of the Job Owner when empty
  notes text,
  row_key text not null unique,                  -- number + title: a second import updates instead of duplicating
  suggestions jsonb,
  link_status text not null default 'new' check (link_status in ('new', 'linked', 'ignored')),
  project_id bigint references public.projects (id) on delete set null,
  transaction_id bigint references public.transactions (id) on delete set null,
  auto_linked boolean not null default false,
  linked_at timestamptz,
  linked_by uuid references public.profiles (id) on delete set null,
  imported_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.sheet_proposals is 'FIN-m: rows of the Sales Projections sheet waiting for a project (same review as Portal.io proposals)';
create index sheet_proposals_status_idx on public.sheet_proposals (link_status);
create index sheet_proposals_number_idx on public.sheet_proposals (main_number);
create trigger sheet_proposals_touch before update on public.sheet_proposals
  for each row execute function app.touch_updated_at();
alter table public.sheet_proposals enable row level security;
create policy "sheet proposals read" on public.sheet_proposals for select to authenticated
  using ((select app.has_permission('administrative.transactions.view_page')) or (select app.has_permission('administrative.finance.view_page')));

-- The sheet's key on each Transaction it wrote or adopted (<row id>:proposal, <row id>:2024-03, <row id>:2023).
alter table public.transactions add column sheet_ref text;
create unique index transactions_sheet_ref_key on public.transactions (sheet_ref) where sheet_ref is not null and deleted_at is null;
