-- INV-e Stock flow (SPEC §9.1 INV-e, Fred 2026-10-13): a list of stock locations instead of free text,
-- and the purchase data of a unit received into stock.

-- 1. Stock locations: a utility list (readable by everyone, edited by whoever manages the lists).
create table public.stock_locations (
  id bigint generated by default as identity primary key,
  title text,
  name text not null,
  kind text not null default 'Other' check (kind in ('Warehouse', 'Van', 'Site', 'Other')),
  employee_id bigint references public.employees (id) on delete set null,
  active boolean not null default true,
  locked boolean not null default false,
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null,
  archived_at timestamptz,
  deleted_at timestamptz
);
comment on table public.stock_locations is 'INV-e: where stock units sit (Warehouse, each van, a site). Stock › Location picks from here; the text on stock_items / stock_movements stays the location name.';
create unique index stock_locations_name_key on public.stock_locations (lower(name)) where deleted_at is null;
create index on public.stock_locations (created_by);
create index on public.stock_locations (updated_at desc);
create trigger before_write before insert or update on public.stock_locations for each row execute function app.record_before_write();
create trigger audit after insert or update on public.stock_locations for each row execute function app.record_audit();
alter table public.stock_locations enable row level security;
create policy "view" on public.stock_locations for select to authenticated using (true);
create policy "create" on public.stock_locations for insert to authenticated with check ((select app.can_manage_utility()));
create policy "modify" on public.stock_locations for update to authenticated using ((select app.can_manage_utility())) with check ((select app.can_manage_utility()));
grant select, insert, update on public.stock_locations to authenticated;
insert into app.record_types (table_name, label, module, resource, parent_table, parent_column, lock_resource, sensitive_columns)
values ('stock_locations', 'Stock Locations', 'utility', null, null, null, null, '{}');

insert into public.stock_locations (name, title, kind) values
  ('Warehouse', 'Warehouse', 'Warehouse'),
  ('Van Branca', 'Van Branca', 'Van'),
  ('Van Preta', 'Van Preta', 'Van');

-- 2. Units point at a location; the old free text (Sortly paths, "CRESTRON RMA"…) becomes Warehouse (Fred).
alter table public.stock_items
  add column location_id bigint references public.stock_locations (id) on delete set null,
  add column supplier_id bigint references public.suppliers (id) on delete set null,
  add column po_number text,
  add column received_on date,
  add column purchased_for_project_id bigint references public.projects (id) on delete set null;
comment on column public.stock_items.location_id is 'INV-e: the stock location; location (text) keeps its name for the ledger and the Stock by location card';
create index on public.stock_items (location_id);

update public.stock_items set location = 'Warehouse' where deleted_at is null and (location is null or location <> 'Warehouse');
update public.stock_items set location_id = (select id from public.stock_locations where name = 'Warehouse') where deleted_at is null;

-- 3. The ledger keeps the purchase data of a receipt.
alter table public.stock_movements
  add column supplier_id bigint references public.suppliers (id) on delete set null,
  add column po_number text,
  add column unit_cost numeric(12,2);
