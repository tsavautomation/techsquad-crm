-- ADM-a Sign in as (SPEC §9.1 ADM-a, Fred 2026-10-14: "as a system administrator i would like to be able to
-- impersonate or login as anyone i want"). Every time an administrator takes over a login it is written here.
create table public.impersonations (
  id bigint generated by default as identity primary key,
  admin_id uuid not null references public.profiles (id) on delete cascade,
  target_id uuid not null references public.profiles (id) on delete cascade,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);
comment on table public.impersonations is 'ADM-a: who signed in as whom, and when they came back.';
alter table public.impersonations enable row level security;
create policy "admins read" on public.impersonations for select to authenticated using (app.is_sysadmin());
grant select on public.impersonations to authenticated;
