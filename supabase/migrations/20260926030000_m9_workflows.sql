-- M9: workflows (SPEC §6, decisions of 2026-09-25):
--   Project Proposal — moved by Office Management, Project Manager, COO, Admin, System Administrators
--   Punch List       — moved by everyone who can edit punch items + Technicians
--   Stock Status     — moved by Admin, System Administrators; starts when a Stock record is created (Q10)
--   Help Desk        — imported but inactive (never used in WebAuthor)
-- Moving a record runs inside one database function (all-or-nothing), which may update the
-- record's status field even when the record is locked (submitted).

create table public.workflows (
  id text primary key,
  name text not null,
  table_name text not null unique,
  start_on text not null check (start_on in ('submit', 'create')),
  active boolean not null default true
);

create table public.workflow_levels (
  id bigint generated by default as identity primary key,
  workflow_id text not null references public.workflows (id) on delete cascade,
  place smallint not null,
  title text not null,
  color text,
  is_start boolean not null default false,
  -- [{ "field": "job_status", "value": "Surveying" }] applied when a record enters this level
  field_updates jsonb not null default '[]',
  allow_comments boolean not null default true,
  unique (workflow_id, place)
);

-- Who may act on records at this level ("recipients" in WebAuthor).
create table public.workflow_level_groups (
  level_id bigint not null references public.workflow_levels (id) on delete cascade,
  group_id smallint not null references public.groups (id) on delete cascade,
  primary key (level_id, group_id)
);

create table public.workflow_outcomes (
  id bigint generated by default as identity primary key,
  level_id bigint not null references public.workflow_levels (id) on delete cascade,
  place smallint not null,
  title text not null,
  -- goto: move to target_level_id · override: user picks any level · unsubmit: leave the workflow and unlock
  kind text not null default 'goto' check (kind in ('goto', 'override', 'unsubmit')),
  target_level_id bigint references public.workflow_levels (id) on delete cascade,
  check ((kind = 'goto') = (target_level_id is not null))
);

-- Where each record currently is.
create table public.record_workflow_state (
  table_name text not null,
  record_id bigint not null,
  workflow_id text not null references public.workflows (id),
  level_id bigint not null references public.workflow_levels (id),
  entered_at timestamptz not null default now(),
  entered_by uuid references public.profiles (id) on delete set null,
  primary key (table_name, record_id)
);
create index record_workflow_state_level_idx on public.record_workflow_state (level_id);

-- Timeline ("WF Timeline" in WebAuthor's Summary block).
create table public.workflow_events (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id bigint not null,
  workflow_id text not null references public.workflows (id),
  from_level_id bigint references public.workflow_levels (id),
  to_level_id bigint references public.workflow_levels (id),
  outcome text not null,
  comment text,
  actor uuid references public.profiles (id) on delete set null,
  at timestamptz not null default now()
);
create index workflow_events_record_idx on public.workflow_events (table_name, record_id, at desc);

