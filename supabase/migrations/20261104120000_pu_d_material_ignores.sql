-- PU-d (Fred 2026-11-04): the equipment installed / staged on a job is laid over its materials pick list (computed on
-- read from stock_items, never stored). A unit the list has no line for is an "extra"; the buyer adds it to the
-- list (a manual project_materials line) or ignores it. The ignores are the only thing stored here.
create table public.project_material_ignores (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  product_id bigint references public.products (id) on delete cascade,
  model text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  check (product_id is not null or model is not null)
);
comment on table public.project_material_ignores is 'PU-d: units on a job (Stock: On Project / Separated) whose product the materials list has no line for, and the buyer chose to ignore. By product, or by model when the unit has no product.';
create unique index project_material_ignores_product_key on public.project_material_ignores (project_id, product_id) where product_id is not null;
create unique index project_material_ignores_model_key on public.project_material_ignores (project_id, lower(model)) where product_id is null and model is not null;
alter table public.project_material_ignores enable row level security;
create policy "purchasers read" on public.project_material_ignores for select to authenticated using ((select app.can_purchase()));
create policy "purchasers write" on public.project_material_ignores for insert to authenticated with check ((select app.can_purchase()));
create policy "purchasers delete" on public.project_material_ignores for delete to authenticated using ((select app.can_purchase()));
grant select, insert, delete on public.project_material_ignores to authenticated;
