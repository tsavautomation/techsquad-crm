-- wa_messages: one row per WhatsApp notification the capture PC forwards (device + notif_id make a resend harmless).
-- wa_tasks:    what Claude made of it: category, priority, customer, phone, system, one-line summary, details;
--              the team works the board (status, assigned to).
-- Only the CRM (service role) writes messages; people with the WhatsApp permission read and work the board.
-- The capture side's manual test may have left two empty tables of the same names: dropped here when empty.

do $$
declare v boolean;
begin
  if to_regclass('public.wa_messages') is not null then
    execute 'select exists (select 1 from public.wa_messages)' into v;
    if v then raise exception 'public.wa_messages already has rows; the F28 migration expected the manual-test tables to be empty'; end if;
  end if;
  if to_regclass('public.wa_tasks') is not null then
    execute 'select exists (select 1 from public.wa_tasks)' into v;
    if v then raise exception 'public.wa_tasks already has rows; the F28 migration expected the manual-test tables to be empty'; end if;
  end if;
end $$;
drop table if exists public.wa_tasks cascade;
drop table if exists public.wa_messages cascade;
drop function if exists public.wa_touch_updated_at();

create table public.wa_messages (
  id bigint generated by default as identity primary key,
  source text not null default 'whatsapp',
  device text not null,
  notif_id bigint not null,
  captured_at timestamptz not null default now(),
  chat text not null,
  sender text,
  body text not null,
  created_at timestamptz not null default now(),
  unique (device, notif_id)
);
comment on table public.wa_messages is 'F28: WhatsApp notifications forwarded by the capture PC (source stays for a later email feed)';
create index wa_messages_captured_idx on public.wa_messages (captured_at desc);

create table public.wa_tasks (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.wa_messages (id) on delete cascade,
  occurred_at timestamptz not null,
  chat text not null,
  customer text,
  phone text,
  category text not null default 'fyi' check (category in ('service_call', 'follow_up', 'quote', 'scheduling', 'fyi')),
  priority text not null default 'normal' check (priority in ('urgent', 'normal', 'low')),
  system text,
  summary text not null,
  details text,
  status text not null default 'open' check (status in ('open', 'in_progress', 'done', 'dismissed')),
  assigned_to text,
  triage text not null default 'ai' check (triage in ('ai', 'fallback')),
  triage_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.wa_tasks is 'F28: Claude''s reading of each WhatsApp message, worked as a shared board on /whatsapp';
create index wa_tasks_occurred_idx on public.wa_tasks (occurred_at desc);
create index wa_tasks_status_idx on public.wa_tasks (status);
create unique index wa_tasks_message_idx on public.wa_tasks (message_id);
create trigger wa_tasks_touch before update on public.wa_tasks
  for each row execute function app.touch_updated_at();

