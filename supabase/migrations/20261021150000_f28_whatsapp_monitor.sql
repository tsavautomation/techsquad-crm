alter table public.wa_messages enable row level security;
alter table public.wa_tasks enable row level security;
-- No insert policy: only the ingest route (service role) adds rows.
create policy "whatsapp read messages" on public.wa_messages for select to authenticated
  using ((select app.has_permission('whatsapp.page.view')));
create policy "whatsapp read tasks" on public.wa_tasks for select to authenticated
  using ((select app.has_permission('whatsapp.page.view')));
create policy "whatsapp work tasks" on public.wa_tasks for update to authenticated
  using ((select app.has_permission('whatsapp.page.view')))
  with check ((select app.has_permission('whatsapp.page.view')));

